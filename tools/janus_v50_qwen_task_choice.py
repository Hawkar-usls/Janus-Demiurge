#!/usr/bin/env python3
"""Qwen G2 research-only JANUS task choice with a strict GitHub Actions firewall.

The neural model is only a proposer. NO_ACTION is valid. Unparseable model
responses never execute. Direct workflow IDs, GitHub paths and permissions are
not generated by any LLM. One proposal maximum per source-verified v5.0 packet.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

from tools import essence_v46_oracle_descendant as v46
from tools import essence_v48_recurrent_state as ancestry
from tools import janus_v50_ai_agency as agency

SCHEMA="janus.agency.qwen_research_task_proposal/5.0"
CHOICES={
    "BEETLE_JSON_DISCOVERY":"janus-beetle-director.yml",
    "TOPA_JSON_CHECK":"janus-topa-scout-epistemic.yml",
}
ABSTAIN="NO_ACTION"


def exact_choice(text):
    if not isinstance(text,str) or len(text)>256:
        return ABSTAIN,"INVALID_OR_OVERSIZED_MODEL_REPLY"
    cleaned=text.strip().strip(chr(96)).strip()
    if cleaned in CHOICES:
        return cleaned,"BOUNDED_TASK_SELECTED"
    if cleaned==ABSTAIN:
        return ABSTAIN,"MODEL_EXPLICIT_ABSTENTION"
    return ABSTAIN,"MODEL_REPLY_NOT_SINGLE_ALLOWLIST_TOKEN"


def validate_packet(packet):
    agency.check(packet)
    if (packet.get("schema")!=agency.SCHEMA
            or packet.get("source_beetle_intent")!="EXPLICIT_USER_DISCOVERY_STEERING"
            or packet.get("beetle_task_id")!="janus_json_registry_provenance_audit"
            or packet.get("native_model",{}).get("native_proposed_this_user_task") is not False
            or packet.get("production_write_authority") is not False
            or packet.get("sentinel_dispatch") is not False
            or set(packet.get("allowed_local_workflows",[])) != set(CHOICES.values())):
        raise ValueError("UNAUTHORIZED_AI_ACTION_SOURCE_PACKET")
    return packet


def create_receipt(packet,raw):
    validate_packet(packet)
    selection,verdict=exact_choice(raw)
    record={
        "schema":SCHEMA,
        "source_packet_sha256":packet["receipt_sha256"],
        "source_commit":packet["source_commit"],
        "model_id":v46.MODEL,
        "model_revision":v46.REVISION,
        "inherited_parent_adapter_sha256":ancestry.GEN2_SHA,
        "inherited_parent_lineage_sha256":ancestry.GEN2_LINEAGE,
        "native_janus_selected":packet["native_model"]["selected_action"],
        "native_janus_patch_action_authorized":False,
        "model_raw_response":raw[:256],
        "model_choice":selection,
        "model_choice_verdict":verdict,
        "dispatch_workflow":CHOICES.get(selection),
        "model_has_arbitrary_workflow_authority":False,
        "source_is_independently_proven_science":False,
        "model_decision_grants_production_authority":False,
        "sentinel_dispatch":False,
        "new_weights_created":False,
        "topa_source_integrity_required":True,
    }
    return agency.sealed(record)


def verify_receipt(packet,receipt):
    agency.check(receipt)
    expected=create_receipt(packet,receipt.get("model_raw_response"))
    if receipt!=expected:
        raise ValueError("MODEL_CHOICE_OR_PARENT_PROVENANCE_TAMPER")
    if (receipt["dispatch_workflow"] is not None and
            receipt["dispatch_workflow"] not in packet["allowed_local_workflows"]):
        raise ValueError("MODEL_DISPATCH_OUTSIDE_CANONICAL_WORKFLOWS")
    return receipt


def infer_choice(model_dir,packet):
    import torch
    from peft import PeftModel
    from tools.essence_v47_repo_peer_evolution import answer_text
    validate_packet(packet)
    ancestry.check_model(model_dir,ancestry.GEN2_SHA,ancestry.GEN2_LINEAGE)
    torch.manual_seed(5001)
    tk,base=v46.tokenizer_and_base({})
    model=PeftModel.from_pretrained(base,str(model_dir),
                                   is_trainable=False).to("cpu").eval()
    prompt=(
        "You are the experimental JANUS research scheduler; you may ONLY choose"
        " one bounded read-only research task. Return exactly ONE allowed token,"
        " no punctuation, no prose. If uncertain, return NO_ACTION.\n"
        "BEETLE_JSON_DISCOVERY = ask the existing Beetle Director to search"
        " for JSON provenance and counterevidence.\n"
        "TOPA_JSON_CHECK = rerun the existing TOPA Scout verification contract.\n"
        "NO_ACTION = abstain.\n"
        "The source showed HOLD for neural generalization, and no new truth"
        " can be inferred from a SHA or another model's agreement.\n"
        "Choose one token:"
    )
    return answer_text(tk,model,[
        {"role":"system","content":"Research task selector only. You cannot run code or use external tools."},
        {"role":"user","content":prompt}
    ],24)


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--packet",required=True)
    p.add_argument("--model",required=True)
    p.add_argument("--out",required=True)
    args=p.parse_args()
    packet=validate_packet(agency.read(args.packet))
    response=infer_choice(args.model,packet)
    result=create_receipt(packet,response)
    target=Path(args.out)
    if target.exists() or target.is_symlink():
        raise ValueError("NO_OVERWRITE_AI_CHOICE")
    target.parent.mkdir(parents=True,exist_ok=True)
    target.write_text(json.dumps(result,indent=2,ensure_ascii=False,sort_keys=True)+"\n")
    print(json.dumps({"choice":result["model_choice"],"status":result["model_choice_verdict"],
                      "packet_id":result["source_packet_sha256"],
                      "actual_workflow_dispatch":False,
                      "production_authority":False},sort_keys=True))


if __name__=="__main__":
    main()
